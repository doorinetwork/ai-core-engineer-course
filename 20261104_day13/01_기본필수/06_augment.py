from pathlib import Path
import os
import cv2
import numpy as np

# ============================================================
# 1. 작업 폴더 설정
# ============================================================
# 제공 코드: 어느 작업 폴더에서 실행해도 현재 파일 옆의 입력을 읽습니다.
# OpenCV에는 영문 상대 경로를 전달합니다. 원본 파일은 덮어쓰지 않습니다.
# 이 .py 파일이 있는 폴더를 현재 작업 폴더로 바꿈
os.chdir(Path(__file__).resolve().parent)

# ============================================================
# 2. 이미지 읽기 및 좌우 반전 (TODO B06)
# ============================================================
# scene.png를 BGR (240, 320, 3)로 읽음
image = cv2.imread("scene.png")
# >>> TODO B06
# cv2.flip(image, 1)로 좌우 반전한 flipped를 만드세요. 세로 반전은 flipCode=0입니다.
# cv2.flip(src, flipCode) : 이미지를 뒤집은 새 배열 반환(원본 image는 그대로)
#   src=image     : 입력 BGR 배열
#   flipCode=1    : 좌우 반전(세로축 기준) -> x 좌표 0 <-> 319
#   flipCode=0    : 상하 반전(가로축 기준)
#   flipCode=-1   : 좌우 + 상하 모두
# 예: 왼쪽 위 빨강 패치(x=30) -> 오른쪽 위(x=289)로 이동
flipped = cv2.flip(image, 1)
# <<< TODO B06

# ============================================================
# 3. 밝기 +30 조절
# ============================================================
# 음수 beta를 사용해도 절댓값 반전이 생기지 않도록 float에서 clip합니다.
# 메서드 체인을 한 단계씩:
#   image.astype(np.float32) : uint8 -> float32, 255를 넘는 값도 표현 가능
#   + 30                     : 모든 채널 값에 30을 더함
#   np.clip(..., 0, 255)     : 0보다 작으면 0, 255보다 크면 255로 제한
#   .astype(np.uint8)        : 다시 이미지용 0~255 정수로 변환
# 예: 240 + 30 = 270 -> 255 / 0 + 30 = 30
# 주의: uint8에서 바로 + 30을 하면 250 + 30 = 280 -> 24처럼 넘쳐서(오버플로) 밝던 곳이 어두워짐
bright = np.clip(image.astype(np.float32) + 30, 0, 255).astype(np.uint8)

# ============================================================
# 4. 비교 그림 만들기 및 저장
# ============================================================
# cv2.hconcat([a, b, c]) : 높이·dtype이 같은 배열을 가로로 이어 붙임
#   [image, flipped, bright] : 왼쪽 원본 / 가운데 좌우반전 / 오른쪽 밝기 +30
# 결과 shape: (240, 320×3, 3) = (240, 960, 3)
comparison = cv2.hconcat([image, flipped, bright])

cv2.imwrite("p06_comparison.png", comparison)
print("왼쪽 원본 / 가운데 좌우반전 / 오른쪽 +30 밝기")
print("비교 그림 Shape:", comparison.shape)
# 최솟값 30 : 원래 0이던 픽셀이 +30
# 최댓값 255 : 225 이상이던 픽셀이 clip으로 255에 고정
print("밝기 범위:", int(bright.min()), int(bright.max()))
