"""실습 04: 다른 행의 통계나 정답을 사용하지 않는 파생 열 하나를 만듭니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# 경로를 다루기 위해 Python 표준 라이브러리 pathlib에서 Path를 가져온다.
from pathlib import Path
# 데이터 처리를 위해 외부 라이브러리 Pandas를 import한다.
import pandas as pd
# 배열 생성 및 수치 연산을 위해 외부 라이브러리 numpy를 가져온다.
import numpy as np

# -----------------------------------------------------------------------------
# 데이터 읽기
# -----------------------------------------------------------------------------
# 이 Python 파일이 있는 경로에 있는 requests.csv 파일을 읽어 raw에 저장한다. 
raw = pd.read_csv(Path(__file__).resolve().parent / "requests.csv")

# -----------------------------------------------------------------------------
# 파생 열 만들기 
# -----------------------------------------------------------------------------
# features (type: DataFrame, 100행 × 1열): raw에서 input_chars 열만 골라 복사한 표이다.
#   - raw[["input_chars"]] : 대괄호를 두 겹으로 쓰면 결과가 Series(1차원)가 아니라 열 1개짜리 DataFrame(2차원)이 된다.
#     DataFrame이어야 뒤에서 새 열을 옆에 붙일 수 있다.
#   - .copy() : 복사본을 따로 만든다. 복사하지 않으면 features를 고칠 때 raw까지 함께 바뀔 수 있고 pandas가 경고를 낸다.
#   - failed(분류 정답)와 elapsed_ms(회귀 정답)를 고르지 않는 이유: 정답을 특성으로 넣으면 모델이 답을 보고 푸는 정보 누수가 된다.
features = raw[["input_chars"]].copy()
# features["log_input_chars"] (type: Series[float], 길이 100): 각 행의 글자 수 x를 log(1 + x)로 바꾼 새 열이다.
#   - np.log1p(x) = log(1 + x)이다. log(x)가 아니라 log1p를 쓰는 이유는 x가 0일 때 log(0)은 -무한대가 되지만 log1p(0) = 0으로 안전하기 때문이다.
#   - 로그 변환을 하는 이유: 글자 수는 203~2381처럼 범위가 넓고 큰 값 쪽으로 길게 퍼져 있다. 로그를 씌우면 큰 값의 차이가 줄어들어
#     5.3~7.8 정도의 좁은 범위로 모이고, 거리나 선형 관계를 쓰는 모델이 극단값에 덜 휘둘린다.
#   - 이 계산은 같은 행의 input_chars 하나만 쓰고 평균·최댓값 같은 다른 행의 통계나 정답을 전혀 쓰지 않는다.
#     그래서 split 전에 계산해도 valid/test 정보가 train으로 새어 들어가지 않는다.
#   - input_chars가 NaN인 행은 결과도 NaN으로 남는다. 빈 값 채우기는 이 단계가 아니라 Pipeline의 imputer가 train 기준으로 맡는다.
#   - 쉽게 말해, 1000자와 2000자의 차이를 "두 배"라는 비율로 보도록 숫자를 눌러 주는 작업이다.
features["log_input_chars"] = np.log1p(features["input_chars"])

# -----------------------------------------------------------------------------
# 결과 확인
# -----------------------------------------------------------------------------
# 앞의 5행을 소수점 셋째 자리까지 반올림해 행 번호 없이 출력한다.
#   - .head() : 기본값으로 앞 5행만 고른다.
#   - .round(3) : 화면에서 읽기 쉽게 소수점 셋째 자리로 반올림한다. 저장된 값 자체는 바꾸지 않는다.
#   - .to_string(index=False) : 왼쪽의 행 번호(0, 1, 2, ...)를 빼고 표를 문자열로 만든다.
print(features.head().round(3).to_string(index=False))
# features.shape (type: tuple[int, int]): (행 수, 열 수)이다. (100, 2)가 나오면 행은 그대로이고 열만 1개 늘어난 것이다.
print("행/열:", features.shape)
# raw.columns.tolist() (type: list[str]): 원본 표의 열 이름 목록이다. 9개 그대로이면 원본에 새 열이 섞이지 않았다는 뜻이다.
print("원본 열:", raw.columns.tolist())