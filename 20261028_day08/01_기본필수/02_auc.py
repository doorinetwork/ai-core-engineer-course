"""실습 02: AUC에는 0/1 판정이 아니라 실패 클래스의 연속 점수를 넣습니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# [외부 라이브러리] scikit-learn의 metrics 모듈: 모델 예측을 채점하는 함수 모음이다.
#   - roc_auc_score: 연속 점수로 ROC 곡선 아래 면적(AUC, 0~1)을 계산한다. 1이면 완벽한 줄 세우기, 0.5면 무작위 수준이다.
#   - roc_curve    : 기준값(threshold)을 높은 쪽부터 낮춰 가며 각 기준에서의 FPR과 TPR을 계산해 ROC 곡선의 점들을 돌려준다.
from sklearn.metrics import roc_auc_score, roc_curve

# -----------------------------------------------------------------------------
# 정답과 확률 준비하기
# -----------------------------------------------------------------------------
# y: 실제 정답이다. 0은 성공(음성), 1은 관심 클래스인 실패(양성)이다. 음성 2건, 양성 2건이다.
y = [0, 0, 1, 1]
# score: 모델이 각 건에 매긴 "실패(1)일 가능성" 점수이다. y와 같은 위치끼리 짝이 된다.
#   - 0/1 판정(pred)이 아니라 연속 점수를 쓰는 이유: AUC는 순서(누가 더 위험한가)를 평가하므로,
#     0/1로 뭉개면 같은 1끼리 순서 정보가 사라져 AUC가 왜곡된다.
#   - 음성 점수: 0.10, 0.40 / 양성 점수: 0.35, 0.80
#   - 양성 0.35가 음성 0.40보다 낮다는 점이 이 예제의 핵심이다. 이 한 쌍 때문에 AUC가 1이 되지 못한다.
score = [0.10, 0.40, 0.35, 0.80]

# -----------------------------------------------------------------------------
# AUC 계산
# -----------------------------------------------------------------------------
# auc: ROC 곡선 아래 면적이다. 이 예제에서는 0.75이다.
#   - 인자 순서는 반드시 (실제값, 점수)이다. y_true가 먼저, y_score가 나중이다.
#   - 두 번째 인자로 0/1 예측이 아닌 연속 점수 score를 넣어야 순서 정보가 살아 있다.
#   - 실무에서 모델을 쓸 때는 model.predict_proba(X)[:, 1]처럼 "클래스 1(실패)의 확률 열"을 넣는다.
auc = roc_auc_score(y, score)

# -----------------------------------------------------------------------------
# ROC 곡선
# -----------------------------------------------------------------------------
# roc_curve: ROC 곡선의 세가지 값을 반환한다.
#   - fpr: 각 기준에서 음성(성공) 중 실패로 잘못 경보한 비율 = FP / (FP + TN)이다.
#   - tpr: 각 기준에서 양성(실패) 중 실패로 찾아낸 비율 = TP / (TP + FN)이다. Recall과 같다.
#   - thresholds: 사용한 기준값들이다. "점수 >= 기준이면 실패로 판정"한다.
fpr, tpr, thresholds = roc_curve(y, score)

# -----------------------------------------------------------------------------
# 결과 출력
# -----------------------------------------------------------------------------
# FPR 배열을 소수 둘째 자리로 반올림해 리스트로 바꿔 출력한다. 
# 결과: [0.0, 0.0, 0.5, 0.5, 1.0]
print("FPR:", fpr.round(2).tolist())
# TPR 배열을 같은 방식으로 출력한다. 결과: [0.0, 0.5, 0.5, 1.0, 1.0]
#   - FPR과 같은 위치끼리 묶으면 ROC 곡선의 점 (0,0) → (0,0.5) → (0.5,0.5) → (0.5,1) → (1,1)이 된다.
print("TPR:", tpr.round(2).tolist())
# AUC를 소수 둘째 자리까지 출력한다. 결과: AUC: 0.75
print(f"AUC: {auc:.2f}")
# 손으로 확인할 과제를 안내한다. 양성 2개 × 음성 2개 = 4쌍을 비교해 "양성 점수가 더 높은 쌍의 비율"을 구하면 AUC와 같다.
#   - 0.80 > 0.10 (맞음), 0.80 > 0.40 (맞음), 0.35 > 0.10 (맞음), 0.35 > 0.40 (틀림) → 4쌍 중 3쌍 = 3/4 = 0.75
print("양성 점수 0.35·0.80과 음성 점수 0.10·0.40을 네 번 비교하세요.")
