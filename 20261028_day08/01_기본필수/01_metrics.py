"""실습 01: 실제 실패 6건인 손계산 예제입니다. 아직 모델을 학습하지 않습니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# [외부 라이브러리] scikit-learn의 metrics 모듈: 모델 예측을 채점하는 함수 모음이다.
#   - confusion_matrix: 정답/예측 조합별 개수(TN, FP, FN, TP)를 2x2 표로 센다.
#   - accuracy_score  : 전체 중 맞힌 비율을 계산한다.
#   - precision_score : "실패라고 예측한 것" 중 진짜 실패의 비율을 계산한다.
#   - recall_score    : "진짜 실패" 중 실패라고 찾아낸 비율을 계산한다.
#   - f1_score        : Precision과 Recall의 조화평균을 계산한다. 이 코드에서는 직접 계산한 F1과 대조하는 확인용으로만 쓴다.
from sklearn.metrics import confusion_matrix, accuracy_score, precision_score, recall_score, f1_score

# -----------------------------------------------------------------------------
# 정답과 예측
# -----------------------------------------------------------------------------
# 실제 정답 레이블 정의 (총 20건: 성공 0이 14건, 관심 클래스인 실패 1이 6건)
y = [0]*14 + [1]*6
# pred: 20개 예측값을 담는다.
# TP=2, FP=4, FN=4, TN=10을 나타내는 모델 예시
pred = [0]*10 + [1]*4 + [0]*4 + [1]*2

# -----------------------------------------------------------------------------
# 혼동행렬
# -----------------------------------------------------------------------------
# 행은 실제, 열은 예측입니다. 1은 좋은 결과가 아니라 관심 클래스인 '실패'입니다.
print("혼동행렬(행 실제 / 열 예측, 성공0·실패1)")
# labels=[0, 1]로 지정하여 행과 열의 순서를 [성공 0, 실패 1]로 고정한다.
print(confusion_matrix(y, pred, labels=[0, 1]))

# -----------------------------------------------------------------------------
# 지표 계산 및 결과 출력
# -----------------------------------------------------------------------------
# acc: 정확도 = (TP+TN) / 전체 = (2+10) / 20 = 0.600이다.
#   accuracy는 분모가 항상 전체 건수(20)라 0이 될 수 없으므로 zero_division 인자를 받지 않는다.
acc = accuracy_score(y, pred)
# precision: 정밀도 = TP / (TP+FP) = 2 / (2+4) = 0.333이다. "실패 경보" 6번 중 2번만 진짜였다는 뜻이다.
#   zero_division=0: 모델이 실패를 한 번도 예측하지 않아 분모(TP+FP)가 0이면 경고 대신 0을 돌려준다.
precision = precision_score(y, pred, zero_division=0)
# recall: 재현율 = TP / (TP+FN) = 2 / (2+4) = 0.333이다. 실제 실패 6건 중 2건만 찾아냈다는 뜻이다.
#   zero_division=0: 데이터에 실제 실패가 하나도 없어 분모(TP+FN)가 0이면 0을 돌려준다.
recall = recall_score(y, pred, zero_division=0)
# f1: F1 = 2 × Precision × Recall / (Precision + Recall) = 2 × 0.333 × 0.333 / 0.667 = 0.333이다.
#   zero_division=0: Precision과 Recall이 모두 0인 경우 분모가 0이 되어버리므로 0을 돌려준다.
f1 = f1_score(y, pred, zero_division=0)
print(f"Accuracy={acc:.3f}, Precision={precision:.3f}, Recall={recall:.3f}, F1={f1:.3f}")
print("실제 실패 6건 중 발견: 2건")
