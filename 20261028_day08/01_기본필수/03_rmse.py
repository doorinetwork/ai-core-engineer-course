"""실습 03: 같은 회귀 문제에서도 주 지표에 따라 후보의 순서가 달라집니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# [외부 라이브러리] scikit-learn의 metrics 모듈: 모델 예측을 채점하는 함수 모음이다.
#   - mean_absolute_error     : MAE(평균 절대 오차)를 계산한다. 오차 |실제 - 예측|을 모두 더해 개수로 나눈 값이다.
#   - root_mean_squared_error : RMSE(평균 제곱 오차의 제곱근)를 계산한다. 오차를 제곱해 평균낸 뒤 제곱근을 씌운 값이다.
#   - 두 지표 모두 단위가 y와 같은 ms이고, 값이 작을수록 좋은 모델이다.
from sklearn.metrics import mean_absolute_error, root_mean_squared_error

# -----------------------------------------------------------------------------
# 정답과 예측 준비
# -----------------------------------------------------------------------------
# 실제 요청 실행시간 레이블을 밀리초(ms) 단위의 리스트로 정의한다.
y = [100, 200, 300, 400] 
# 오차 특성이 서로 다른 두 모델 A와 B의 예측값 딕셔너리를 정의한다.
#   - "A": 앞의 3건은 정확히 맞히고, 마지막 1건만 480으로 예측해 80ms를 크게 틀린다. 오차 = [0, 0, 0, 80]
#   - "B": 4건 모두 30ms씩 높게 예측한다. 오차 = [30, 30, 30, 30]
#   - 두 모델은 일부러 "한 번 크게 틀림"과 "고르게 조금씩 틀림"으로 대비되게 만든 예제이다.
predictions = {"A": [100, 200, 300, 480], "B": [130, 230, 330, 430]}

# -----------------------------------------------------------------------------
# MAE·RMSE 계산과 출력
# -----------------------------------------------------------------------------
for name, pred in predictions.items():
    # mae (type: float): 오차 절댓값의 평균이다.
    #   - MAE는 오차를 크기 그대로 더하므로, 80ms 한 번은 20ms 네 번과 똑같은 무게를 가진다.
    mae = mean_absolute_error(y, pred)
    # rmse (type: float): 오차를 제곱해 평균낸 뒤 제곱근을 씌운 값이다.
    #   - 제곱을 하면 80ms 오차는 6400이 되어 30ms 오차(900)의 7배가 넘는다. 그래서 큰 오차 하나가 RMSE를 크게 끌어올린다.
    #   - 마지막에 제곱근을 씌우는 이유: 제곱하면 단위가 ms²가 되므로, 다시 ms 단위로 되돌려 MAE와 나란히 읽을 수 있게 한다.
    rmse = root_mean_squared_error(y, pred)
    # 모델 이름과 두 지표를 소수 첫째 자리(:.1f)까지, 단위 ms를 붙여 출력한다.
    print(f"{name}: MAE={mae:.1f}ms, RMSE={rmse:.1f}ms")
print("실행시간 단위 ms를 함께 적으세요. 교차검증은 06번에서 이어집니다.")
