"""실습 01: 입력을 질문으로 나누는 트리를 만듭니다. 성능 평가가 아닌 원리 예제입니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# 외부 라이브러리(scikit-learn). 목적: 결정 트리 분류 모델을 쓰기 위해.
from sklearn.tree import DecisionTreeClassifier

# -----------------------------------------------------------------------------
# 예제 데이터 준비 (입력 특성 1열: 글자 수, 정답: 실패 여부)
# -----------------------------------------------------------------------------
X = [[100], [200], [300], [700], [800], [900]]
y = [0, 0, 0, 1, 1, 1]  # 같은 순서의 정답: 성공 0, 실패 1

# -----------------------------------------------------------------------------
# 결정 트리 모델 생성
# -----------------------------------------------------------------------------
# max_depth=1: 분기는 1번으로 제한한다. 
# random_state=42: 무작위 순서를 고정해 실행할 때마다 항상 같은 트리가 나오게 한다.
model = DecisionTreeClassifier(max_depth=1, random_state=42)

# -----------------------------------------------------------------------------
# 학습: X와 y로 model 학습
# -----------------------------------------------------------------------------
model.fit(X, y)

# -----------------------------------------------------------------------------
# 예측: 250과 850을 예측하여 prediction에 넣는다
# -----------------------------------------------------------------------------
# predict: 학습(fit) 과정에서 찾은 분기 기준(500.0)을 적용해 새 샘플이 속할 잎을 결정하고 예측값을 낸다.
# 학습 데이터 X가 2차원 리스트였던 것처럼 예측 데이터 또한 2차원 배열 형태로 입력해야 한다: [[250], [850]]
# [[250], [850]]은 새 입력이다.
prediction = model.predict([[250], [850]])

# 3. 학습 결과 및 예측 확인
# tree_.threshold[0]: 첫 번째 노드(루트)에서 분기 기준으로 결정된 임계값(500.0)
print("분기 기준:", model.tree_.threshold[0])
print("250·850 예측:", prediction.tolist())
