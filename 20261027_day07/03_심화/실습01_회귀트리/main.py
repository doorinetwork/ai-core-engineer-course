"""실습 01 심화: 회귀 트리의 잎별 평균을 표로 확인합니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# [표준 라이브러리] pathlib.Path: 파일·폴더 경로를 객체로 다루는 클래스이다.
from pathlib import Path
# [외부 라이브러리] pandas: 표 형태 데이터를 다루는 라이브러리이다. pd라는 짧은 이름으로 쓴다.
import pandas as pd
# [외부 라이브러리] sklearn.tree.DecisionTreeRegressor: scikit-learn의 회귀용 결정 트리 클래스이다.
from sklearn.tree import DecisionTreeRegressor

# -----------------------------------------------------------------------------
# 학습 데이터 준비
# -----------------------------------------------------------------------------
# 입력 특성 X이다. 행 6개, 열(특성) 1개인 2차원 리스트이다. (type: list)
X = [[100], [200], [300], [700], [800], [900]]
# 정답(타깃) y이다. (type: list)
y = [100, 120, 140, 700, 720, 740]

# -----------------------------------------------------------------------------
# 모델 만들기와 학습
# -----------------------------------------------------------------------------
# 회귀 트리 모델 객체를 만든다. (type: DecisionTreeRegressor)
model = DecisionTreeRegressor(max_depth=1, random_state=42)
# fit은 학습을 마친 model 자신을 돌려주고, 학습 결과(분기 기준·잎 평균)는 model 안에 저장된다.
model.fit(X, y)

# -----------------------------------------------------------------------------
# 잎별 평균 표 만들기
# -----------------------------------------------------------------------------
# model.apply(X)는 각 행이 트리를 따라 내려가 도착한 노드 번호 배열이다. 
# 깊이 1 트리는 뿌리가 0번, 왼쪽 잎이 1번, 오른쪽 잎이 2번이므로 [1, 1, 1, 2, 2, 2]가 나온다.
rows = pd.DataFrame({"leaf": model.apply(X), "actual": y})
# 잎 번호별로 묶어서 행 개수와 정답 평균을 계산한다. (type: DataFrame)
# as_index=False는 leaf를 인덱스로 숨기지 않고 일반 열로 남겨서, CSV에 leaf 열이 그대로 저장되게 한다.
# count=("actual", "size")는 각 잎에 도착한 행 수이고, mean_ms=("actual", "mean")은 그 행들의 정답 평균이다.
means = rows.groupby("leaf", as_index=False).agg(count=("actual", "size"), mean_ms=("actual", "mean"))

# -----------------------------------------------------------------------------
# 결과 저장
# -----------------------------------------------------------------------------
# 이 파일이 있는 폴더 아래의 outputs 폴더 경로이다. (type: Path)
OUT = Path(__file__).resolve().parent / "outputs"
# outputs 폴더를 만든다. exist_ok=True는 폴더가 이미 있어도 오류 없이 넘어가게 한다.
OUT.mkdir(exist_ok=True)
# 잎별 평균 표를 CSV로 저장한다.
means.to_csv(OUT / "leaf_means.csv", index=False, encoding="utf-8-sig")

# -----------------------------------------------------------------------------
# 결과 출력과 예측 확인
# -----------------------------------------------------------------------------
# 뿌리 노드(0번)의 분기 기준값을 출력한다. (type: float)
print("분기 기준:", model.tree_.threshold[0])
# 잎별 평균 표를 행 번호 없이 출력한다. 
print(means.to_string(index=False))
# 학습에 없던 값 250, 850, 1200을 예측하고 리스트로 바꿔 출력한다. (type: list)
print("250·850·1200 예측:", model.predict([[250], [850], [1200]]).tolist())
