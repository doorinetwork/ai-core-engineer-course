"""실습 01 응용: 잎 안 정답의 평균으로 숫자를 예측합니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# 결정 트리 모델을 쓰기 위해 외부 라이브러리 scikit-learn에서 DecisionTreeRegressor를 import한다.
from sklearn.tree import DecisionTreeRegressor

# -----------------------------------------------------------------------------
# 학습 데이터 준비
# -----------------------------------------------------------------------------
X = [[100], [200], [300], [700], [800], [900]]
y = [100, 120, 140, 700, 720, 740]

# -----------------------------------------------------------------------------
# 결정 트리 모델 생성
# -----------------------------------------------------------------------------
# max_depth=1: 분기는 1번으로 제한한다. 
# random_state=42: 무작위 순서를 고정해 실행할 때마다 항상 같은 트리가 나오게 한다.
model = DecisionTreeRegressor(max_depth=1, random_state=42)
# -----------------------------------------------------------------------------
# 학습
# -----------------------------------------------------------------------------
model = model.fit(X, y)

# -----------------------------------------------------------------------------
# 예측
# -----------------------------------------------------------------------------
# predict: 학습(fit) 과정에서 찾은 분기 기준(500.0)을 적용해 새 샘플이 속할 잎을 결정하고 예측값을 낸다.
# 학습 데이터 X가 2차원 리스트였던 것처럼 예측 데이터 또한 2차원 배열 형태로 입력해야 한다.
# [[250], [850], [1200]]은 새 입력이다.
# 250은 기준(500) 이하라 왼쪽 잎으로 가고, 왼쪽 잎 정답 평균 120을 받는다.
# 850과 1200은 기준보다 크므로 오른쪽 잎으로 가고, 오른쪽 잎 정답 평균 720을 받는다.
prediction = model.predict([[250], [850], [1200]])

# -----------------------------------------------------------------------------
# 학습 결과 및 예측 확인
# -----------------------------------------------------------------------------
# tree_.threshold[0]: 첫 번째 노드(루트)에서 분기 기준으로 결정된 임계값(500.0)
# 500은 왼쪽 무리의 가장 큰 값 300과 오른쪽 무리의 가장 작은 값 700의 정확한 가운데이다. 트리는 인접한 두 값의 중간점을 기준 후보로 삼는다.
print("분기 기준:", model.tree_.threshold[0])
print("250·850·1200 예측:", prediction.tolist())
# y[:3] (type: list): 왼쪽 잎에 들어간 정답 [100, 120, 140]이다. 평균은 120.0이다.
# y[3:] (type: list): 오른쪽 잎에 들어간 정답 [700, 720, 740]이다. 평균은 720.0이다.
# 손으로 구한 평균이 위 예측값과 정확히 같으므로, "회귀 트리의 예측값 = 잎 안 정답의 평균"임을 검증한다.
print("왼쪽 평균:", sum(y[:3]) / 3, "오른쪽 평균:", sum(y[3:]) / 3)
print("1200은 학습 범위 밖입니다. 트리도 기존 잎 값으로 예측합니다.")
