"""실습 03 Basic · 일반 prose 전용 cleaning.

실습 03 Cleaning · 기본필수
- 역할: 일반 문장(prose)의 줄바꿈과 가로 공백만 정리하고 문단 경계·숫자·조건은 그대로 보존한다
- 기능: unify_newlines()(D24-03-B01) CRLF/CR -> LF, reduce_horizontal_spaces()(D24-03-B02) 공백·탭 축약
- 결과: outputs/cleaning.json (정제 전 repr 문자열과 정제 후 문자열)
"""

# ============================================================
# 1. 경로 설정 및 모듈 import
# ============================================================
from pathlib import Path
import re, sys
# HERE : 이 파일이 있는 실습 폴더 (outputs/ 저장 기준)
HERE = Path(__file__).resolve().parent
# HERE.parents[1] : <수준>/<실습>_주석 기준 두 단계 위 = mentee 폴더
# -> mentee 를 import 경로 맨 앞에 넣어 coursekit 패키지를 불러온다
sys.path.insert(0, str(HERE.parents[1]))
# 제공 모듈 coursekit/io.py: 공통 경로(DATA)·JSON 읽기/저장·완료 메시지
from coursekit.io import DATA, save_json, show_success

# ============================================================
# 2. 줄바꿈을 LF로 통일 (TODO D24-03-B01)
# ============================================================
# Windows(\r\n)·옛 Mac(\r) 줄바꿈을 모두 \n 하나로 바꾼다.
# - '출석\r\n안내' -> '출석\n안내'
# - '출석\r안내'   -> '출석\n안내'
# - 줄을 합치지 않으므로 문단 경계(빈 줄)는 유지
def unify_newlines(text: str) -> str:
    # BEGIN D24-03-B01
    # 개념·실무 해설(mentor 원문): CRLF와 CR을 LF로 통일하되, 줄바꿈이 나타낸 문단 경계는 그대로 남깁니다. NFC는 응용 단계에서 별도 정규화합니다.
    # TODO D24-03-B01 완료: CRLF·CR 줄바꿈을 LF로 바꿉니다. 문단의 줄을 하나로 합치지 않습니다.
    # 순서 주의: '\r\n'을 먼저 바꾼다. '\r'을 먼저 바꾸면 '\r\n'이 '\n\n'(빈 줄 추가)이 된다
    return text.replace('\r\n', '\n').replace('\r', '\n')
    # END D24-03-B01

# ============================================================
# 3. 가로 공백 축약 (TODO D24-03-B02)
# ============================================================
# 줄마다 연속된 공백·탭을 한 칸으로 줄이고 줄 앞뒤 공백을 지운다.
# - '10분  초과는'  -> '10분 초과는'
# - 빈 줄 ''        -> '' 그대로 (문단 경계 보존)
# - 전체 앞뒤 공백·빈 줄은 마지막 .strip()으로 제거
def reduce_horizontal_spaces(text: str) -> str:
    # 줄 단위 변환이므로 빈 줄이 사라지지 않습니다.
    # BEGIN D24-03-B02
    # 개념·실무 해설(mentor 원문): 일반 prose의 연속된 가로 공백만 축약하고 줄바꿈 경계는 유지합니다. 코드 들여쓰기와 표의 탭 구분에는 같은 규칙을 적용하지 않습니다.
    # TODO D24-03-B02 완료: 연속된 공백·탭을 한 칸으로 줄이고 좌우 공백을 제거합니다. 빈 줄은 보존합니다.
    # 처리 순서
    # - text.split('\n')            : 줄 단위로 나눔 (줄바꿈 자체는 건드리지 않음)
    # - re.sub(r'[ \t]+', ' ', line) : 공백·탭 1개 이상을 공백 1개로
    # - .strip()                     : 줄 앞뒤 공백 제거
    # - '\n'.join(...)               : 다시 줄바꿈으로 연결
    # 주의: 코드 들여쓰기·탭 구분 표에는 이 규칙을 쓰면 구조가 깨진다 (심화 03에서 구분)
    return '\n'.join(re.sub(r'[ \t]+', ' ', line).strip() for line in text.split('\n')).strip()
    # END D24-03-B02

# ============================================================
# 4. 실행 흐름 (main)
# ============================================================
# CRLF·중복 공백이 섞인 예문을 정제하고 핵심 문장과 빈 줄이 남았는지 확인한다.
def main():
    # 정제 전 예문: 공백 3칸, CRLF 줄바꿈, 빈 줄 1개, '10분  초과' 공백 2칸
    text = '출석   안내\r\n\r\n10분  초과는 결석.\r\n단,  사전 승인 시 예외.'
    # 줄바꿈 통일 -> 공백 축약 순서로 적용
    # 결과: '출석 안내\n\n10분 초과는 결석.\n단, 사전 승인 시 예외.'
    cleaned = reduce_horizontal_spaces(unify_newlines(text))
    # 숫자·조건 문장이 그대로 남았는지 확인
    assert '10분 초과는 결석.' in cleaned
    # 문단 경계(빈 줄)가 사라지지 않았는지 확인
    assert '\n\n' in cleaned
    # 저장 dict 키 : 의미
    # - before : repr(text). \r\n이 눈에 보이도록 이스케이프 문자열로 기록
    # - after  : 정제 결과 문자열
    out = save_json(HERE, 'cleaning.json', {'before': repr(text), 'after': cleaned})
    show_success('03 Basic', out)

# ============================================================
# 5. 스크립트 직접 실행 시 main() 호출
# ============================================================
if __name__ == '__main__':
    main()
