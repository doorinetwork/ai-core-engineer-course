"""실습 04: 은닉 너비에 따라 파라미터 수가 변합니다. 학습 성능 비교는 아닙니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# 외부 라이브러리. 목적: 딥러닝용 Tensor를 다루기 위해 불러온다.
import torch
# 외부 라이브러리(torch의 하위 모듈). 목적: 신경망 층을 만들기 위해 불러온다. 
# 기능: nn.Linear 같은 층(layer) 클래스와 손실 함수 등을 제공한다.
from torch import nn

# -----------------------------------------------------------------------------
# 재현성 확보 (난수 시드 고정)
# -----------------------------------------------------------------------------
# torch.manual_seed(42): PyTorch 난수 생성기의 시작점을 42로 고정한다.
#   nn.Linear는 만들어질 때 가중치와 편향을 무작위 값으로 초기화한다. 시드를 고정하면 몇 번을 실행해도 같은 초기 가중치가 나오므로
#   출력 logits 값이 매번 같아져 결과를 비교·검증할 수 있다. 42 자체에 특별한 의미는 없고, 관례적으로 많이 쓰는 고정값이다.
#   반드시 모델을 만들기 "전에" 호출해야 한다. 모델을 만든 뒤에 호출하면 이미 초기화된 가중치에는 영향을 주지 못한다.
torch.manual_seed(42)

# -----------------------------------------------------------------------------
# 입력 데이터 준비
# -----------------------------------------------------------------------------
# X (type: torch.Tensor, dtype: torch.float32, shape: (4, 2)): 모든 값이 1.0인 샘플 4개, 특성 2개짜리 입력이다.
#   torch.ones는 기본 dtype이 float32이므로 nn.Linear의 float32 가중치와 그대로 행렬곱이 된다.
#   값이 모두 1인 이유: 이 실습은 값의 의미가 아니라 shape와 파라미터 수를 확인하는 것이 목적이므로 가장 단순한 입력을 쓴다.
#   세 모델 모두 같은 X를 쓰므로, 결과 차이는 오직 은닉 너비(hidden) 때문에 생긴다.
X = torch.ones(4, 2)

# -----------------------------------------------------------------------------
# 은닉 너비별 모델 만들기와 비교
# -----------------------------------------------------------------------------
# hidden (type: int): 은닉층의 뉴런 수(너비)이다. 리스트 [4, 8, 16] (type: list)의 값을 하나씩 꺼내 세 번 반복한다.
#   반복할 때마다 모델을 새로 만들므로, 이전 반복의 model은 버려지고 새 구조의 model로 바뀐다.
for hidden in [4, 8, 16]:
    # ReLU가 없으면 Linear 두 개를 이어도 수학적으로 Linear 하나와 같은 직선(선형) 계산이 되어, 은닉층을 넓혀도 표현력이 늘지 않는다.
    # 마지막에 softmax를 넣지 않는 이유: 분류 학습에 쓰는 CrossEntropyLoss가 내부에서 softmax를 직접 계산하므로, 모델은 softmax 전 점수(logits)를 내야 한다.
    #   softmax를 모델에 또 넣으면 손실 계산 때 softmax가 두 번 적용되어 기울기가 작아지고 학습이 잘못된다.
    # model (type: nn.Sequential): 아래 세 모듈을 순서대로 연결한 신경망이다. model(X)를 호출하면 세 모듈의 forward가 차례로 실행된다.
    #   - nn.Linear(2, hidden) (type: nn.Linear): 입력 특성 2개를 은닉 뉴런 hidden개로 바꾸는 층이다.
    #       2는 X의 열 개수(특성 수)와 같아야 한다. weight shape (hidden, 2) = 2×hidden개, bias shape (hidden,) = hidden개 → 3×hidden개이다.
    #   - nn.ReLU() (type: nn.ReLU): 음수는 0으로 바꾸고 양수는 그대로 둔다. 학습할 파라미터는 0개이므로 파라미터 수에 영향을 주지 않는다.
    #   - nn.Linear(hidden, 2) (type: nn.Linear): 은닉 뉴런 hidden개를 클래스 점수 2개로 바꾸는 출력층이다.
    #       in_features hidden은 앞 층의 출력 수와 같아야 한다. weight shape (2, hidden) = 2×hidden개, bias shape (2,) = 2개 → 2×hidden + 2개이다.
    model = nn.Sequential(nn.Linear(2, hidden), nn.ReLU(), nn.Linear(hidden, 2))
    # logits (type: torch.Tensor, dtype: torch.float32, shape: (4, 2)): 샘플 4개 각각의 클래스 2개 원시 점수이다.
    #   shape 변화: (4, 2) → Linear(2, hidden) → (4, hidden) → ReLU → (4, hidden) → Linear(hidden, 2) → (4, 2).
    #   은닉 너비는 중간 shape만 바꾸고, 최종 출력 shape는 hidden과 상관없이 항상 (4, 2)이다.
    #   logits는 확률이 아니므로 음수일 수 있고 합이 1이 아니다. 학습 전 무작위 가중치이므로 값 자체에는 아직 의미가 없다.
    logits = model(X)
    # count (type: int): 모델의 학습 파라미터 총개수이다.
    #   model.parameters() (type: generator): Linear1.weight, Linear1.bias, Linear2.weight, Linear2.bias를 차례로 꺼내 준다. ReLU는 파라미터가 없어 나오지 않는다.
    #   p.numel() (type: int): 텐서 p 안의 숫자 개수이다. 예: shape (4, 2)이면 8이다.
    #   공식: (2×hidden + hidden) + (2×hidden + 2) = 5×hidden + 2 이다. 너비를 2배로 늘리면 파라미터 수도 거의 2배가 된다.
    count = sum(p.numel() for p in model.parameters())
    # 은닉 너비, 출력 shape(tuple로 바꿔 "(4, 2)"처럼 깔끔하게 표시), 파라미터 수를 한 줄에 출력한다.
    # 예상 출력 (직접 계산한 값이다):
    #   은닉: 4 출력: (4, 2) 파라미터: 22    ← (8 + 4) + (8 + 2) = 22
    #   은닉: 8 출력: (4, 2) 파라미터: 42    ← (16 + 8) + (16 + 2) = 42
    #   은닉: 16 출력: (4, 2) 파라미터: 82   ← (32 + 16) + (32 + 2) = 82
    print("은닉:", hidden, "출력:", tuple(logits.shape), "파라미터:", count)
