"""실습 03: x=3에서 y=x²+2x+1과 기울기를 계산합니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# 외부 라이브러리. 목적: 딥러닝용 Tensor를 다루기 위해 불러온다.
import torch

# -----------------------------------------------------------------------------
# 입력 텐서 만들기
# -----------------------------------------------------------------------------
# x (type: torch.Tensor, 0차원 스칼라, dtype=torch.float32): 미분할 대상 변수이며 값은 3.0이다.
#   requires_grad=True: "이 텐서로 만드는 모든 계산을 기록해 두라"는 표시이다.
#     이 표시가 있어야 나중에 backward()가 x에 대한 기울기를 계산해 x.grad에 저장한다.
#   3.0처럼 실수로 쓰는 이유: 기울기(미분)는 실수 텐서에서만 계산된다. 정수 3으로 만들면 requires_grad=True에서 오류가 난다.
x = torch.tensor(3.0, requires_grad=True)

# -----------------------------------------------------------------------------
# 계산 그래프 만들기 
# -----------------------------------------------------------------------------
# y (type: torch.Tensor, 0차원 스칼라, requires_grad=True): x² + 2x + 1의 계산 결과이며 x=3에서 값은 16.0이다.
#   x ** 2, 2 * x, + 1은 모두 텐서 x에 직접 적용한 텐서 연산이다. 그래서 PyTorch가
#   "제곱 → 곱셈 → 덧셈" 순서를 계산 그래프로 기록하고, y는 그 그래프의 끝(출력)이 된다.
#   x.item()이나 float(x)로 숫자를 꺼내 계산하면 결과가 그래프와 끊긴 일반 숫자가 되어 backward()로 기울기를 구할 수 없다.
#   원래 있던 y = x + 0은 식이 y = x라서 기울기가 1.0으로 나오는 자리표시 코드이므로 실제 식으로 바꾼다.
y = x ** 2 + 2 * x + 1

# -----------------------------------------------------------------------------
# 기울기 계산과 결과 출력
# -----------------------------------------------------------------------------
# backward는 y 값을 바꾸지 않고 x.grad에 기울기를 계산한다.
#   y.backward(): 계산 그래프를 출력 y에서 입력 x 방향으로 거꾸로 따라가며(역전파) 연쇄법칙으로 dy/dx를 구한다.
#   y가 값 하나짜리 스칼라이므로 인자 없이 호출할 수 있다. 결과는 x.grad에 저장되며 반환값은 없다(type: None).
y.backward()
# y.item() (type: float): 0차원 텐서 y에서 Python 실수를 꺼낸다. 출력은 "y: 16.0"이다.
#   기울기 계산이 이미 끝났으므로 여기서 숫자로 꺼내도 그래프에는 영향이 없다.
print("y:", y.item())
# x.grad (type: torch.Tensor, 0차원): backward()가 저장한 dy/dx 값이다. dy/dx = 2x + 2이므로 x=3에서 8.0이다.
#   x.grad.item() (type: float): 그 기울기를 Python 실수로 꺼낸다. 출력은 "dy/dx: 8.0"이다.
#   기울기 8.0의 뜻: x를 아주 조금 늘리면 y는 그 양의 약 8배만큼 늘어난다.
print("dy/dx:", x.grad.item())
