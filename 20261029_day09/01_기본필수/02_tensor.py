"""실습 02: 값뿐 아니라 shape·dtype·device를 같이 확인합니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# 외부 라이브러리. 목적: 딥러닝용 Tensor를 다루기 위해 불러온다.
import torch

# -----------------------------------------------------------------------------
# 0차원·1차원 Tensor 만들기
# -----------------------------------------------------------------------------
# scalar (type: torch.Tensor) 숫자 하나 3.0만 담은 0차원 Tensor(스칼라)이다.
# 괄호 없이 숫자 하나를 넣었으므로 shape는 ()가 된다.
# 3.0처럼 소수점이 있는 값을 넣었기 때문에 dtype은 PyTorch 기본 실수형인 torch.float32로 정해진다.
scalar = torch.tensor(3.0)
# vector (type: torch.Tensor) 숫자 3개를 한 줄로 담은 1차원 Tensor(벡터)이다.
# 리스트 하나에 원소가 3개이므로 shape는 (3,)이고, 실수 값이므로 dtype은 torch.float32이다.
vector = torch.tensor([1.0, 2.0, 3.0])

# -----------------------------------------------------------------------------
# 2차원 Tensor(행렬) 만들기
# -----------------------------------------------------------------------------
# matrix (type: torch.Tensor) 2행 2열의 2차원 Tensor(행렬)이다.
# 리스트 안에 리스트를 넣는 중첩 구조로 써야 2차원이 된다. [1.0, 2.0, 3.0, 4.0]처럼 한 줄로 쓰면 shape가 (4,)인 1차원 벡터가 되어 요구사항을 어긴다.
# 바깥 리스트의 원소 2개가 행(row), 안쪽 리스트의 원소 2개가 열(column)이 되므로 shape는 (2, 2)이다.
# dtype=torch.float32는 자료형을 32비트 실수로 명시한다. 값이 이미 실수라 기본값도 float32이지만, 요구사항이 dtype을 지정했으므로 코드에 직접 적어 의도를 분명히 한다.
# 쉽게 말하면, 숫자 4개를 한 줄로 늘어놓는 대신 2줄 2칸짜리 표 모양으로 정리해 담는 것이다.
matrix = torch.tensor([[1.0, 2.0], [3.0, 4.0]], dtype=torch.float32)
# matrix를 CPU 메모리로 옮긴 Tensor를 다시 matrix에 담는다.
# .to()는 원본을 바꾸지 않고 새 Tensor를 돌려주므로 반드시 변수에 다시 대입해야 한다.
# torch.tensor()로 만든 Tensor는 처음부터 CPU에 있으므로 여기서는 실제 이동이 일어나지 않고, 장치를 명시적으로 고정하는 역할을 한다.
matrix = matrix.to("cpu")

# -----------------------------------------------------------------------------
# shape·dtype·device와 값 확인하기
# -----------------------------------------------------------------------------
# 스칼라의 모양, 자료형, 장치를 출력한다. scalar.shape는 torch.Size 객체이므로 tuple()로 바꿔 ()처럼 보기 쉽게 출력한다.
# 예상 출력: 스칼라: () torch.float32 cpu
print("스칼라:", tuple(scalar.shape), scalar.dtype, scalar.device)
# 벡터의 모양, 자료형, 장치를 출력한다.
# 예상 출력: 벡터: (3,) torch.float32 cpu
print("벡터:", tuple(vector.shape), vector.dtype, vector.device)
# 행렬의 모양, 자료형, 장치를 출력한다. B02가 올바르므로 shape가 (2, 2)로 나온다.
# 예상 출력: 행렬: (2, 2) torch.float32 cpu
print("행렬:", tuple(matrix.shape), matrix.dtype, matrix.device)
# .tolist()로 Tensor를 파이썬 중첩 리스트(type: list)로 바꿔 실제 값을 출력한다. 2차원 Tensor이므로 리스트 안에 리스트가 든 형태로 나온다.
# 예상 출력: 행렬 값: [[1.0, 2.0], [3.0, 4.0]]
print("행렬 값:", matrix.tolist())
