"""실습 04: 2 → 8 → 2 신경망의 순전파를 확인합니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# 외부 라이브러리. 목적: 딥러닝용 Tensor를 다루기 위해 불러온다.
import torch
# 외부 라이브러리(torch의 하위 모듈). 목적: 신경망 층을 만들기 위해 불러온다. 
# 기능: nn.Linear 같은 층(layer) 클래스와 손실 함수 등을 제공한다.
from torch import nn

# -----------------------------------------------------------------------------
# 재현성 확보 (난수 시드 고정)
# -----------------------------------------------------------------------------
# torch.manual_seed(42): PyTorch 난수 생성기의 시작점을 42로 고정한다.
#   nn.Linear는 만들어질 때 가중치와 편향을 무작위 값으로 초기화한다. 시드를 고정하면 몇 번을 실행해도 같은 초기 가중치가 나오므로
#   출력 logits 값이 매번 같아져 결과를 비교·검증할 수 있다. 42 자체에 특별한 의미는 없고, 관례적으로 많이 쓰는 고정값이다.
#   반드시 모델을 만들기 "전에" 호출해야 한다. 모델을 만든 뒤에 호출하면 이미 초기화된 가중치에는 영향을 주지 못한다.
torch.manual_seed(42)

# -----------------------------------------------------------------------------
# 모델 만들기
# -----------------------------------------------------------------------------
# model (type: nn.Sequential): 아래 세 모듈을 순서대로 연결한 신경망이다. model(X)를 호출하면 세 모듈의 forward가 차례로 실행된다.
#   - nn.Linear(2, 8) (type: nn.Linear): 입력 특성 2개를 은닉 뉴런 8개로 바꾸는 층이다. y = x @ W.T + b 를 계산한다.
#       weight shape (8, 2) = 16개, bias shape (8,) = 8개 → 파라미터 24개이다. 2는 입력 특성 수(X의 열 개수)와 같아야 한다.
#   - nn.ReLU() (type: nn.ReLU): 음수를 0으로 바꾸고 양수는 그대로 둔다. 학습할 파라미터는 0개이다.
#       ReLU가 없으면 Linear 두 개를 이어도 결국 Linear 하나와 같은 직선(선형) 계산이 되므로, 곡선 같은 복잡한 경계를 배울 수 없다.
#   - nn.Linear(8, 2) (type: nn.Linear): 은닉 뉴런 8개를 클래스 점수 2개로 바꾸는 출력층이다.
#       weight shape (2, 8) = 16개, bias shape (2,) = 2개 → 파라미터 18개이다.
model = nn.Sequential(nn.Linear(2, 8), nn.ReLU(), nn.Linear(8, 2))

# -----------------------------------------------------------------------------
# 입력 데이터 준비
# -----------------------------------------------------------------------------
# X (type: torch.Tensor, dtype: torch.float32, shape: (4, 2)): 샘플 4개, 특성 2개인 입력 데이터이다.
#   행 하나가 샘플 하나, 열 하나가 특성 하나이다. 첫 번째 차원 4는 배치 크기(batch), 두 번째 차원 2는 특성 수이다.
#   값을 1.0처럼 소수로 쓴 이유: nn.Linear의 가중치가 float32이므로 입력도 float32여야 행렬곱이 된다. 정수(int64)로 만들면 dtype 불일치 오류가 난다.
X = torch.tensor([[1.0, 2.0], [3.0, 4.0], [0.0, 1.0], [2.0, 0.0]])

# -----------------------------------------------------------------------------
# 순전파 (forward)
# -----------------------------------------------------------------------------
# logits (type: torch.Tensor, dtype: torch.float32, shape: (4, 2)): 샘플 4개 각각에 대한 클래스 2개의 원시 점수이다.
#   model(X)는 내부적으로 Linear(2,8) → ReLU → Linear(8,2)의 forward를 순서대로 호출한다.
#   shape 변화: (4, 2) → Linear(2,8) → (4, 8) → ReLU → (4, 8) → Linear(8,2) → (4, 2). 배치 크기 4는 끝까지 유지된다.
#   model.forward(X)가 아니라 model(X)로 호출해야 PyTorch가 hook 등 내부 처리를 함께 실행한다.
#   logits는 확률이 아니다. 음수일 수도 있고 두 값의 합이 1이 아니다. 확률이 필요하면 softmax를 따로 적용하고,
#   학습 때는 CrossEntropyLoss에 softmax 전 logits를 그대로 넣는다.
logits = model(X)

# -----------------------------------------------------------------------------
# 결과 확인
# -----------------------------------------------------------------------------
# X.shape (type: torch.Size)를 tuple로 바꿔 출력한다. tuple로 바꾸면 "torch.Size([4, 2])" 대신 "(4, 2)"처럼 깔끔하게 보인다.
# 예상 출력: 입력: (4, 2)
print("입력:", tuple(X.shape))
# logits.shape (type: torch.Size)를 tuple로 바꿔 출력한다.
# 예상 출력: 출력: (4, 2)  
print("출력:", tuple(logits.shape))
# logits.shape (type: torch.Size)를 tuple로 바꿔 출력한다. 
# 예상 출력: 출력: (4, 2)  
print("출력:", tuple(logits.shape))
# model.parameters() (type: generator): 모델에 등록된 학습 가능한 Parameter(가중치·편향 텐서)를 하나씩 꺼내 주는 반복자이다.
#   순서: Linear1.weight(8,2), Linear1.bias(8,), Linear2.weight(2,8), Linear2.bias(2,). ReLU는 파라미터가 없어 나오지 않는다.
# p.numel() (type: int): 텐서 p에 들어 있는 숫자(스칼라)의 개수이다. 예: shape (8, 2)이면 16이다.
# sum(...) (type: int): 모든 파라미터의 숫자 개수를 더한 값이다. 16 + 8 + 16 + 2 = 42이다.
# 예상 출력: 파라미터 수: 42   
print("파라미터 수:", sum(p.numel() for p in model.parameters()))
# logits는 원시 점수이다. 이 시점에는 학습하지 않았다.
#   가중치가 무작위 초기값 그대로이므로 logits 값 자체에는 아직 의미가 없다. 이 실습에서 확인할 것은 값이 아니라 shape와 파라미터 수이다.
