"""실습 03: 수동 Gradient Descent와 gradient 누적을 구분합니다."""
# -----------------------------------------------------------------------------
# 라이브러리 불러오기
# -----------------------------------------------------------------------------
# [표준 라이브러리] pathlib.Path: 파일·폴더 경로를 객체로 다루는 클래스이다.
#   - 목적: 결과 CSV를 저장할 outputs 폴더 경로를 운영체제와 관계없이 안전하게 만들기 위해 쓴다.
from pathlib import Path
# [표준 라이브러리] csv: CSV 파일을 읽고 쓰는 모듈이다.
#   - 목적: step별 갱신 기록(records)을 updates.csv로 저장하기 위해 쓴다.
import csv
# 외부 라이브러리. 목적: 딥러닝용 Tensor를 다루기 위해 불러온다.
import torch

# -----------------------------------------------------------------------------
# 학습할 파라미터 준비
# -----------------------------------------------------------------------------
# w (type: torch.Tensor, 0차원 float32 스칼라): 경사하강법으로 찾아갈 파라미터이다. 시작값은 0.0이다.
#   requires_grad=True: "이 텐서로 만든 계산을 기록해 두었다가 w에 대한 미분값을 w.grad에 채워 달라"는 뜻이다.
#   이것이 없으면 loss.backward()를 불러도 w.grad가 만들어지지 않아 기울기를 얻을 수 없다.
#   0.0처럼 소수로 써야 float 텐서가 된다. 정수 0으로 만들면 int 텐서가 되어 requires_grad=True를 쓸 수 없다.
w = torch.tensor(0.0, requires_grad=True)

# -----------------------------------------------------------------------------
# 수동 Gradient Descent 반복 (10 step)
# -----------------------------------------------------------------------------
# records (type: list): step마다 [step, 갱신 전 w, 기울기, 갱신 후 w, 갱신 후 loss] 한 줄씩 쌓는 기록 목록이다.
records = []
for step in range(1, 11):
    # before (type: float): 이번 step에서 갱신하기 전의 w 값이다.
    #   .item()은 0차원 텐서를 파이썬 float으로 꺼낸다. 텐서 그대로 저장하면 w가 바뀔 때 기록도 같이 바뀌어 보이므로 숫자로 꺼내 둔다.
    before = w.item()
    # loss (type: torch.Tensor, 0차원): 손실 함수 (w - 4)^2 의 현재 값이다. w = 4일 때 0으로 가장 작다.
    #   w가 requires_grad=True이므로 이 계산 과정(빼기 → 제곱)이 계산 그래프로 기록된다.
    loss = (w - 4) ** 2
    # backward(): 계산 그래프를 거꾸로 따라가며 d(loss)/dw = 2(w - 4) 를 계산해 w.grad에 "더한다".
    #   덮어쓰는 것이 아니라 더하는 것이 핵심이다. 그래서 아래에서 매번 grad.zero_()로 비워 줘야 한다.
    loss.backward()
    # gradient (type: float): 이번 step의 기울기 값 2(w - 4)이다. 음수면 w를 키워야 loss가 줄어든다는 뜻이다.
    gradient = w.grad.item()
    # torch.no_grad(): 이 블록 안의 연산은 계산 그래프에 기록하지 않는다.
    #   w 갱신은 "학습 규칙"이지 "모델 계산"이 아니므로 미분 대상이 되면 안 된다.
    #   또한 requires_grad=True인 잎(leaf) 텐서를 추적 중에 제자리(in-place) 수정하면 RuntimeError가 나므로 반드시 이 블록 안에서 바꾼다.
    with torch.no_grad():
        # 경사하강법 갱신 규칙: w ← w − lr × (d loss / d w).
        #   기울기의 반대 방향으로 움직여야 loss가 줄어든다. 기울기가 음수(-8)면 w는 커지고, 양수면 작아진다.
        #   lr(learning rate, 학습률) = 0.1: 기울기에 곱하는 보폭이다. 이 문제에서는 매 step 4까지의 거리가 0.8배로 줄어든다.
        # w -= ...: 새 텐서를 만들지 않고 w 자체(같은 객체)를 제자리 수정한다.
        #   w = w - ... 로 쓰면 w가 새 텐서로 바뀌어 requires_grad와 w.grad를 잃고, 다음 반복에서 w.grad가 None이 된다.
        #   w.grad (type: torch.Tensor, 0차원): 방금 backward()로 채워진 기울기이다.
        lr = 0.1
        w -= lr * w.grad
    # grad.zero_(): w.grad 값을 0으로 제자리 초기화한다. 끝의 밑줄(_)은 "제자리 수정"을 뜻한다.
    #   backward()는 기울기를 더해 넣으므로, 비우지 않으면 다음 step의 기울기에 이번 기울기가 섞여 틀린 방향·크기로 움직인다.
    w.grad.zero_()
    # 이번 step의 기록 한 줄 (type: list[int, float, float, float, float])을 records에 추가한다.
    #   w.item(): 갱신 후 w 값이다.
    #   (w.detach()-4).square().item(): 갱신 후 w로 다시 계산한 loss 값이다.
    #   detach()는 계산 그래프에서 떼어 낸 텐서를 만든다. 기록용 계산이 그래프에 남지 않게 하려고 쓴다.
    records.append([step, before, gradient, w.item(), (w.detach()-4).square().item()])

# -----------------------------------------------------------------------------
# 갱신 기록 출력
# -----------------------------------------------------------------------------
# r (type: list): records의 한 줄이다. 순서대로 step, w_before, gradient, w_after, loss_after이다.
#   round(값, 6): float32 오차로 생기는 긴 꼬리를 잘라 소수 6자리까지만 보여 준다.
# 손으로 계산한 예상 출력이다(float32 계산이므로 마지막 자리는 미세하게 다를 수 있다).
#   1 0.0 -8.0 0.8 10.24
#   2 0.8 -6.4 1.44 6.5536
#   3 1.44 -5.12 1.952 4.194304
#   4 1.952 -4.096 2.3616 2.684355
#   5 2.3616 -3.2768 2.68928 1.717987
#   6 2.68928 -2.62144 2.951424 1.099512
#   7 2.951424 -2.097152 3.161139 0.703687
#   8 3.161139 -1.677722 3.328911 0.45036
#   9 3.328911 -1.342177 3.463129 0.28823
#   10 3.463129 -1.073742 3.570503 0.184467
# 갱신 후 w는 4 - 4×0.8^step 이므로 4에 점점 가까워지고, loss는 매 step 0.64배로 줄어든다.
for r in records:
    print(r[0], round(r[1], 6), round(r[2], 6), round(r[3], 6), round(r[4], 6))

# -----------------------------------------------------------------------------
# gradient 누적 확인 (zero_()를 하지 않으면 어떻게 되는가)
# -----------------------------------------------------------------------------
# u (type: torch.Tensor, 0차원 float32 스칼라): 누적 현상을 보여 주기 위한 별도의 파라미터이다. 값은 1.0이다.
u = torch.tensor(1.0, requires_grad=True)
# 첫 번째 순전파 u**2 와 역전파이다. d(u^2)/du = 2u = 2.0 이 u.grad에 들어간다(처음에는 None이었으므로 2.0이 된다).
(u**2).backward()
# first (type: float): 첫 역전파 직후의 기울기 2.0이다.
first = u.grad.item()
# 같은 그래프를 다시 쓰는 대신 새로운 순전파 그래프를 만든다.
#   backward()가 끝나면 그 그래프는 메모리에서 해제되므로 같은 그래프로 두 번 backward()하면 오류가 난다. 그래서 u**2를 새로 계산한다.
#   이번에도 기울기는 2.0인데, 사이에 zero_()가 없으므로 기존 2.0에 더해져 u.grad는 4.0이 된다.
(u**2).backward()
# 출력: "초기화하지 않은 gradient: 2.0 -> 4.0". 기울기가 덮어써지지 않고 누적된다는 것을 숫자로 보여 준다.
print("초기화하지 않은 gradient:", first, "->", u.grad.item())

# -----------------------------------------------------------------------------
# 결과 저장
# -----------------------------------------------------------------------------
# out (type: Path): 이 파이썬 파일이 있는 폴더 아래의 outputs 폴더 경로이다.
#   __file__ 기준으로 잡으므로 어느 폴더에서 실행하든 항상 같은 위치에 저장된다.
out = Path(__file__).resolve().parent / "outputs"
# exist_ok=True: 폴더가 이미 있어도 오류 없이 넘어간다. 
out.mkdir(exist_ok=True)
# updates.csv를 쓰기 모드("w")로 연다.
#   encoding="utf-8-sig": 파일 앞에 BOM을 붙여 엑셀에서 열어도 한글이 깨지지 않게 한다.
#   newline="": csv 모듈이 줄바꿈을 직접 관리하므로, 윈도우에서 빈 줄이 끼어드는 것을 막는다.
#   f (type: TextIOWrapper): 열린 파일 객체이다. with 블록이 끝나면 자동으로 닫힌다.
with (out / "updates.csv").open("w", encoding="utf-8-sig", newline="") as f:
    # writer (type: csv.writer): f에 CSV 형식으로 쓰는 객체이다.
    # writerow: 머리글 한 줄을 쓴다. writerows: records의 10줄을 한 번에 쓴다(반올림하지 않은 원래 값 그대로).
    writer=csv.writer(f); writer.writerow(["step","w_before","gradient","w_after","loss_after"]); writer.writerows(records)
