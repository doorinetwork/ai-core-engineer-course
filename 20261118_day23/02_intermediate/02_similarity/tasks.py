import numpy as np

# ============================================================
# 2. 내적(Dot product)
# ============================================================
# BEGIN D23-02-I01
def dot(a, b):
    # 같은 위치의 좌표끼리 곱해 모두 더한 내적을 float으로 돌려준다.
    # - a, b   : 같은 길이의 NumPy 1차원 배열
    # - 반환값 : float
    # 예: (1, 0)·(0.8, 0.6) = 1×0.8 + 0×0.6 = 0.8
    # [강사용 정답] D23-02-I01 · dot
    #     같은 위치의 숫자를 곱해 합산하는 내적을 구현하세요.
    #     예: (1,0)·(0.8,0.6)=0.8. 입력 NumPy 배열 2개, 출력 float.
    # 해설 D23-02-I01: 입력을 먼저 확인하고, 핵심 개념을 적용한 다음 결과를 반환합니다.
    # 좌표별 곱을 모두 합산. 내적은 벡터 크기에도 영향을 받습니다.
    # float(...) : NumPy 스칼라(np.float64)를 파이썬 float으로 바꿔 JSON 저장이 쉽게 함
    return float(np.dot(a, b))
# END D23-02-I01

# ============================================================
# 3. Cosine similarity
# ============================================================
# BEGIN D23-02-I02
def cosine(a, b):
    # 내적을 두 벡터 길이의 곱으로 나눈 Cosine similarity를 돌려준다.
    # - 정상 입력        : -1 ~ 1 사이 float (1에 가까울수록 방향이 같음)
    # - 영벡터가 하나라도 : ValueError('zero_vector') (길이 0으로 나눌 수 없음)
    # 예: q=(1, 0), A=(0.8, 0.6) -> 0.8 / (1 × 1) = 0.8
    # [강사용 정답] D23-02-I02 · cosine
    #     내적을 두 벡터 길이의 곱으로 나누어 Cosine similarity를 구하세요.
    #     q=(1,0), A=(0.8,0.6)라면 0.8입니다.
    #     입력: NumPy 배열 2개. 출력: float. 영벡터는 무조건 거부합니다.
    # 해설 D23-02-I02: 입력을 먼저 확인하고, 핵심 개념을 적용한 다음 결과를 반환합니다.
    # ① 길이 ② 분모 확인 ③ 정규화한 내적.
    # np.linalg.norm(x) : 벡터 길이 sqrt(x1² + x2² + ...) -> (0.8, 0.6)의 길이는 1.0
    na = float(np.linalg.norm(a))
    nb = float(np.linalg.norm(b))
    # 1e-12 이하 : 사실상 0인 길이로 보고 거부 (부동소수점 오차 고려)
    if na <= 1e-12 or nb <= 1e-12:
        raise ValueError('zero_vector')
    return dot(a, b) / (na * nb)
# END D23-02-I02

# ============================================================
# 4. L2(유클리드) 거리
# ============================================================
# BEGIN D23-02-I03
def l2(a, b):
    # 두 벡터의 좌표 차이 벡터의 길이(L2 거리)를 돌려준다. 값이 작을수록 가깝다.
    # - a, b   : 같은 길이의 NumPy 1차원 배열
    # - 반환값 : 0 이상의 float
    # 예: (1, 0) - (0.8, 0.6) = (0.2, -0.6) -> sqrt(0.04 + 0.36) = sqrt(0.4) ≈ 0.632456
    # [강사용 정답] D23-02-I03 · l2
    #     두 벡터의 좌표 차이로 L2 거리를 구하세요. 출력 float.
    #     q=(1,0), A=(0.8,0.6) → sqrt(0.4) ≈ 0.6325.
    # 해설 D23-02-I03: 입력을 먼저 확인하고, 핵심 개념을 적용한 다음 결과를 반환합니다.
    # 좌표 간 차이의 길이: 값이 작을수록 가깝습니다.
    return float(np.linalg.norm(a - b))
# END D23-02-I03

# ============================================================
# 5. 단위 벡터로 정규화
# ============================================================
# BEGIN D23-02-I04
def normalize(a):
    # 벡터를 자기 길이로 나눠 길이가 1인 단위 벡터를 새로 만든다.
    # - 정상 입력 : 새 배열 반환 (원본 a는 바뀌지 않음)
    # - 영벡터    : ValueError('zero_vector')
    # 예: (10, 10) -> 길이 14.142136 -> (0.707107, 0.707107)
    # [강사용 정답] D23-02-I04 · normalize
    #     임의 벡터 a를 길이가 1인 단위 벡터로 변환하세요.
    #     기존 배열을 직접 변경하지 않습니다. 영벡터는 ValueError.
    # 해설 D23-02-I04: 입력을 먼저 확인하고, 핵심 개념을 적용한 다음 결과를 반환합니다.
    n = float(np.linalg.norm(a))
    if n <= 1e-12:
        raise ValueError('zero_vector')
    # a / n : 나눗셈은 새 배열을 만든다 (a /= n 처럼 제자리 수정하지 않음)
    return a / n
# END D23-02-I04

# ============================================================
# 6. Dot 순위와 Cosine 순위 비교
# ============================================================
# BEGIN D23-02-I05
def rank_dot_vs_cosine(q, candidates):
    # 후보 벡터들을 Dot 큰 순서와 Cosine 큰 순서로 각각 정렬해 이름 목록 두 개를 돌려준다.
    # - q          : 질문 벡터
    # - candidates : {이름: 벡터} dict (run에서는 U=(1, 0), V=(10, 10))
    # - 반환값     : {'dot': [이름...], 'cosine': [이름...]}
    # 예: q=(1, 0) -> Dot은 V(10) > U(1) 이라 ['V', 'U'], Cosine은 U(1.0) > V(0.707) 이라 ['U', 'V']
    # -> 길이가 큰 벡터가 Dot 순위를 뒤집을 수 있다
    # [강사용 정답] D23-02-I05 · rank_dot_vs_cosine
    #     후보 {이름:벡터}를 Dot 내림차순과 Cosine 내림차순으로 각각 정렬하세요.
    #     결과: {'dot':[이름...], 'cosine':[이름...]}.
    #     크기가 큰 벡터가 Dot 순위를 바꿀 수 있음을 확인합니다.
    # 해설 D23-02-I05: 입력을 먼저 확인하고, 핵심 개념을 적용한 다음 결과를 반환합니다.
    # 동점이면 이름 오름차순으로 정렬하여 결과를 재현 가능하게 만듭니다.
    # sorted(dict) : dict의 키(이름)를 정렬
    # key=(-점수, 이름) : 점수는 큰 순서(음수로 바꿔 오름차순 정렬), 동점이면 이름 순서
    d = sorted(candidates, key = lambda n: (-dot(q, candidates[n]), n))
    c = sorted(candidates, key = lambda n: (-cosine(q, candidates[n]), n))
    return {'dot': d, 'cosine': c}
# END D23-02-I05
