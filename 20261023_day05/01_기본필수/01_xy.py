# -----------------------------------------------------------------------------
# 01 기본필수: CSV에서 입력과 정답을 각각 꺼냅니다.
# -----------------------------------------------------------------------------
# 경로 지정을 위해 파이썬 표준 라이브러리인 Path를 import한다.
from pathlib import Path
# 데이터 처리를 위해 외부 라이브러리로 Pandas를 import한다.
import pandas as pd

# -----------------------------------------------------------------------------
# 파일 경로 지시
# -----------------------------------------------------------------------------
# 현재 Python 파일의 경로가 어디인지(폴더)를 HERE에 저장한다.
# __file__: 파일 경로
# .resolve(): 절대경로 변환
# .parent: 상위 폴더
HERE = Path(__file__).resolve().parent
# 현재 Python 파일과 같은 경로에 있는 requests.csv를 Pandas로 읽어 data에 저장한다. 
# (type:DataFrame)
data = pd.read_csv(HERE / "requests.csv")

# -----------------------------------------------------------------------------
# 입력 꺼내기
# -----------------------------------------------------------------------------
# data로부터 입력글자수(input_chars)와 작업유형(task_type) 2개의 열을 받아 X에 저장한다. 
# (type: DataFrame)
X = data[["input_chars", "task_type"]]
# -----------------------------------------------------------------------------
# 정답 꺼내기
# -----------------------------------------------------------------------------
# data로부터 정답(failed) 열 1개를 받아 y에 저장한다. (type: Series)
# failed는 종료 상태가 실패인 경우 1, 성공인 경우 0으로 코딩한 범주형 데이터이다.
y = data["failed"]

# -----------------------------------------------------------------------------
# 결과 출력
# -----------------------------------------------------------------------------
# X로부터 열 이름을 리스트로 바꿔 출력한다.
print("입력 열:", X.columns.tolist())
# X의 모양을 행과 열의 튜플로 출력한다.
print("X 모양:", X.shape)
# y의 모양을 행과 열의 튜플로 출력한다.
print("y 모양:", y.shape)
# y의 처음 3개 값을 리스트로 바꿔 출력한다.
print("처음 3개 정답:", y.head(3).tolist())
