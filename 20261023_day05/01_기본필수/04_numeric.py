# -----------------------------------------------------------------------------
# 04 기본필수: 결측이 없는 숫자를 train 기준으로 표준화합니다.
# -----------------------------------------------------------------------------
# 데이터 처리를 위해 외부 라이브러리로 Pandas를 import한다.
import pandas as pd
# 표준화를 위해 외부 라이브러리 scikit-learn의 StandardScaler 클레스를 import한다.
from sklearn.preprocessing import StandardScaler

# -----------------------------------------------------------------------------
# 데이터 준비
# -----------------------------------------------------------------------------
# 입력글자수(input_chars)를 이용해 훈련용 train 데이터 3행을 DataFrame으로 입력한다.
train = pd.DataFrame({"input_chars": [100, 200, 300]})
# 입력글자수(input_chars)를 이용해 검증용 valid 데이터 2행을 DataFrame으로 입력한다.
valid = pd.DataFrame({"input_chars": [400, 500]})

# -----------------------------------------------------------------------------
# Fit
# -----------------------------------------------------------------------------
# StandardScaler 클래스로 scaler 객체를 생성한다.
scaler = StandardScaler()
# train 데이터를 기준으로 표준화 기준을 학습해(fit) scaler에 저장한다.
scaler.fit(train)

# -----------------------------------------------------------------------------
# Transform
# -----------------------------------------------------------------------------
# train에서 학습한 평균과 표준편차로 valid를 변환하여 valid_ready에 저장한다. (type: ndarray)
# 이때 valid로 다시 fit하면 검증 데이터가 기준에 섞여 데이터 누수가 되므로 다시 fit하지 않는다.
valid_ready = scaler.transform(valid)

# -----------------------------------------------------------------------------
# 결과 출력
# -----------------------------------------------------------------------------
# scaler가 train에서 배운 평균을 리스트로 바꿔 출력한다.
print("train에서 배운 평균:", scaler.mean_.tolist())
# valid 변환 결과를 소수 셋째 자리까지 반올림하여 출력한다.
print("valid 변환 결과:")
print(valid_ready.round(3))
