# -----------------------------------------------------------------------------
# 02 기본필수: 평균을 어디에서 계산해야 하는지 비교합니다.
# -----------------------------------------------------------------------------

# -----------------------------------------------------------------------------
# 데이터 준비
# -----------------------------------------------------------------------------
# 학습을 위해 train 데이터의 값 2개를 리스트로 저장한다.
train_values = [10, 20]
# 학습에 쓰이지 않고 성능을 확인하는 데 쓰는 valid 데이터의 값 1개를 리스트로 저장한다.
valid_values = [100]

# -----------------------------------------------------------------------------
# train 평균 계산 (올바른 기준)
# -----------------------------------------------------------------------------
# train 값만을 사용해 평균을 계산한다.
train_mean = sum(train_values) / len(train_values)
# -----------------------------------------------------------------------------
# 전체 평균 계산 (잘못된 기준)
# -----------------------------------------------------------------------------
# train과 valid 값을 모두 사용한 전체 데이터의 평균을 내므로, 
# valid의 큰 값으로 인해 전체 평균이 크게 올라간다.
all_values = train_values + valid_values
all_mean = sum(all_values) / len(all_values)

# -----------------------------------------------------------------------------
# 결과 출력
# -----------------------------------------------------------------------------
# train 평균을 소수 둘째 자리까지 반올림하여 출력한다.
print("train 평균:", round(train_mean, 2))
# 전체 평균을 소수 둘째 자리까지 반올림하여 출력한다. 
print("전체 평균(비교만):", round(all_mean, 2))
# 분리하지 않고 전체 평균을 사용하면 valid의 값이 데이터 누수를 일으킨다.
print("실제 전처리에는 train 평균만 사용합니다.")