# -----------------------------------------------------------------------------
# """05 기본필수: qa와 summary를 서로 다른 0/1 열로 표현합니다."""
# -----------------------------------------------------------------------------
# 범주형 데이터 처리를 위해 외부 라이브러리 scikit-learn의 OneHotEncoder 클레스를 import한다.
from sklearn.preprocessing import OneHotEncoder

# -----------------------------------------------------------------------------
# 데이터 준비
# -----------------------------------------------------------------------------
# 훈련용 train 데이터로 2차원 리스트를 입력한다. 데이터는 작업유형(task_type) 열이다.
train = [["qa"], ["summary"], ["qa"]]
# 검증용 valid 데이터로 2차원 리스트를 입력한다.
valid = [["summary"], ["qa"]]

# -----------------------------------------------------------------------------
# Fit
# -----------------------------------------------------------------------------
# one-hot 인코딩을 수행할 encoder를 생성한다.
# sparse_output=False는 결과를 바로 볼 수 있는 숫자 표로 받는다.
encoder = OneHotEncoder(sparse_output=False)
# train 데이터를 기준으로 범주 기준을 학습(fit)하여 encoder에 저장한다.
encoder.fit(train)

# -----------------------------------------------------------------------------
# Transform
# -----------------------------------------------------------------------------
# train에서 학습한 범주 기준을 바탕으로 valid 데이터를 0과 1의 one-hot 벡터로 변환하여 리스트로 저장한다.
valid_ready = encoder.transform(valid).tolist()

# -----------------------------------------------------------------------------
# 결과 출력
# -----------------------------------------------------------------------------
# encoder가 배운 범주를 열 순서대로 리스트로 바꿔 출력한다.
print("열 순서:", encoder.categories_[0].tolist())
# valid의 변환 결과를 출력한다.
print("valid 변환:", valid_ready)
